#!/usr/bin/env python3
"""patch_23_font_5x7.py — замена 3x5 глифов на 5x7 (читаемый шрифт)."""
import re
from pathlib import Path

p = Path('src/main.cpp')
s = p.read_text()
changes = 0

new_glyphs = """    static const uint8_t glyphs[][7] = {
        {0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E},  // 0
        {0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E},  // 1
        {0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F},  // 2
        {0x1F, 0x02, 0x04, 0x02, 0x01, 0x11, 0x0E},  // 3
        {0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02},  // 4
        {0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E},  // 5
        {0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E},  // 6
        {0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08},  // 7
        {0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E},  // 8
        {0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C},  // 9
        {0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11},  // A (10)
        {0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E},  // B
        {0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E},  // C
        {0x1E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1E},  // D
        {0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F},  // E
        {0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10},  // F
        {0x0E, 0x11, 0x10, 0x17, 0x11, 0x11, 0x0F},  // G
        {0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11},  // H
        {0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E},  // I
        {0x07, 0x02, 0x02, 0x02, 0x02, 0x12, 0x0C},  // J
        {0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11},  // K
        {0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F},  // L
        {0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11},  // M
        {0x11, 0x19, 0x15, 0x13, 0x11, 0x11, 0x11},  // N
        {0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E},  // O
        {0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10},  // P
        {0x0E, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0D},  // Q
        {0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11},  // R
        {0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E},  // S
        {0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04},  // T
        {0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E},  // U
        {0x11, 0x11, 0x11, 0x11, 0x0A, 0x0A, 0x04},  // V
        {0x11, 0x11, 0x11, 0x15, 0x15, 0x1B, 0x11},  // W
        {0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11},  // X
        {0x11, 0x11, 0x11, 0x0A, 0x04, 0x04, 0x04},  // Y
        {0x1F, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1F},  // Z (35)
    };"""

pattern = r'    static const uint8_t glyphs\[\]\[5\] = \{.*?\n    \};'
new_s, n = re.subn(pattern, new_glyphs, s, count=1, flags=re.DOTALL)
if n == 1:
    s = new_s; changes += 1
    print("OK: глифы 3x5 → 5x7")
else:
    print("!! не найдена старая таблица [][5]")

old = """    if (code < 0 || code > 25) return;
    for (int row = 0; row < 5; ++row) {
        uint8_t bits = glyphs[code][row];
        for (int col = 0; col < 3; ++col) {
            if (bits & (0x4 >> col)) {
                SDL_FRect p = { x + col * scale, y + row * scale, scale, scale };
                SDL_RenderFillRect(r, &p);
            }
        }
    }"""
new = """    if (code < 0 || code >= 36) return;
    for (int row = 0; row < 7; ++row) {
        uint8_t bits = glyphs[code][row];
        for (int col = 0; col < 5; ++col) {
            if (bits & (0x10 >> col)) {
                SDL_FRect p = { x + col * scale, y + row * scale, scale, scale };
                SDL_RenderFillRect(r, &p);
            }
        }
    }"""
if old in s:
    s = s.replace(old, new, 1); changes += 1
    print("OK: draw_glyph 5x7")

pattern = r"        else if \(\*p == 'T'\) code = 10;.*?else if \(\*p == 'D'\) code = 25;"
new_block = """        else if (*p >= 'A' && *p <= 'Z') code = 10 + (*p - 'A');"""
new_s, n = re.subn(pattern, new_block, s, count=1, flags=re.DOTALL)
if n == 1:
    s = new_s; changes += 1
    print("OK: draw_text — индексы A-Z (10-35)")
else:
    print("!! не найден блок кодов букв в draw_text")

old = "        else if (*p == ' ') { cx += 4.0f * scale; continue; }"
new = "        else if (*p == ' ') { cx += 6.0f * scale; continue; }"
if old in s:
    s = s.replace(old, new, 1); changes += 1
    print("OK: пробел → 6*scale")

old = "        cx += 4.0f * scale;"
new = "        cx += 6.0f * scale;"
if old in s:
    s = s.replace(old, new, 1); changes += 1
    print("OK: шаг между символами → 6*scale")

old = "    return n * 4.0f * scale;"
new = "    return n * 6.0f * scale;"
if old in s:
    s = s.replace(old, new, 1); changes += 1
    print("OK: text_width → n * 6 * scale")

p.write_text(s)
print(f"\nИзменено: {changes}/6")
